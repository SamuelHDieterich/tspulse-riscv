/// e^x at each node, x = -16 + i/64.
float exp_table_nodes[EXP_TABLE_NODES];

// ░█▀▀░█░█░█▀█░█▀▀░▀█▀░▀█▀░█▀█░█▀█░█▀▀
// ░█▀▀░█░█░█░█░█░░░░█░░░█░░█░█░█░█░▀▀█
// ░▀░░░▀▀▀░▀░▀░▀▀▀░░▀░░▀▀▀░▀▀▀░▀░▀░▀▀▀

void exp_table_fill(void) {
    for (int i = 0; i < EXP_TABLE_NODES; i++) {
        // x = -16 + i/64 is exact in float, so every node sits on the grid
        float x = EXP_TABLE_LOWEST + (float)i / EXP_TABLE_PER_UNIT;
        exp_table_nodes[i] = expf(x);
    }
}
