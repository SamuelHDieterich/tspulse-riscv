// y[i] = a[i] + b[i]
// https://docs.pytorch.org/docs/stable/generated/torch.add.html
void add(const float *a, const float *b, float *y, int n) {
    for (int i = 0; i < n; i++) {
        y[i] = a[i] + b[i];
    }
}
