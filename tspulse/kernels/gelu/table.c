/// GELU at each node, x = -8 + i/32.
float gelu_table_nodes[GELU_TABLE_NODES];

// ░█▀▀░█░█░█▀█░█▀▀░▀█▀░▀█▀░█▀█░█▀█░█▀▀
// ░█▀▀░█░█░█░█░█░░░░█░░░█░░█░█░█░█░▀▀█
// ░▀░░░▀▀▀░▀░▀░▀▀▀░░▀░░▀▀▀░▀▀▀░▀░▀░▀▀▀

void gelu_table_fill(void) {
    for (int i = 0; i < GELU_TABLE_NODES; i++) {
        // x = -8 + i/32 is exact in float, so every node sits on the grid
        float x = GELU_TABLE_LOWEST + (float)i / GELU_TABLE_PER_UNIT;
        gelu_table_nodes[i] = gelu_libm(x);
    }
}
